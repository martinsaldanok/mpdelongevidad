const centerGrid = document.querySelector("#centerGrid");
const worldMap = document.querySelector("#worldMap");
const centerDialog = document.querySelector("#centerDialog");
const toast = document.querySelector("#toast");

function t(key) {
  return translations[state.lang][key] || translations.en[key] || key;
}

function icon(name) {
  return `<i data-lucide="${name}"></i>`;
}

function refreshIcons() {
  window.lucide?.createIcons();
}

function translateStatic() {
  document.documentElement.lang = state.lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === state.lang);
  });
}

function formatPrice(value) {
  return new Intl.NumberFormat(state.lang === "de" ? "de-DE" : state.lang === "fr" ? "fr-FR" : state.lang === "es" ? "es-ES" : "en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(value);
}

function specialtyLabel(key) {
  return specialtyNames[key]?.[state.lang] || specialtyNames[key]?.en || key;
}

function filteredCenters() {
  return centers.filter((center) => {
    const byRegion = state.region === "all" || center.region === state.region;
    const byProgram = state.program === "all" || center.program === state.program;
    const byStay = state.stay === "all" || center.stay === state.stay;
    const bySpecialty = state.specialty === "all" || center.specialties.includes(state.specialty);
    return byRegion && byProgram && byStay && bySpecialty;
  });
}

function renderCenters() {
  const items = filteredCenters();
  document.querySelector("#matchCount").textContent = items.length;

  centerGrid.innerHTML = items.length
    ? items
        .map(
          (center) => `
            <article class="center-card">
              <figure>
                <img src="${center.image}" alt="${center.name}">
                <span class="center-badge">${center.badge[state.lang] || center.badge.en}</span>
                <div class="contact-layer">
                  <strong>${t("contactReveal")}</strong>
                  <span>${center.contact}</span>
                  <span>${center.phone}</span>
                  <span>${center.email}</span>
                </div>
              </figure>
              <div class="center-body">
                <div class="center-title-row">
                  <div>
                    <h3>${center.name}</h3>
                    <p>${center.city}, ${center.country}</p>
                  </div>
                  <span class="rating">${icon("star")} ${center.rating}</span>
                </div>
                <p class="center-summary">${center.summary[state.lang] || center.summary.en}</p>
                <div class="specialties">
                  ${center.specialties.map((item) => `<span>${specialtyLabel(item)}</span>`).join("")}
                </div>
                <div class="center-footer">
                  <div class="center-price">
                    <strong>${t("from")} ${formatPrice(center.price)}</strong>
                    <small>${t("perProgram")} · ${center.stay} days</small>
                  </div>
                  <a class="primary-button compact" href="mailto:${center.email}?subject=ForeverX%20introduction%20request">
                    ${icon("mail-check")}
                    ${t("introButton")}
                  </a>
                </div>
              </div>
            </article>
          `
        )
        .join("")
    : `
      <article class="center-card">
        <div class="center-body">
          <h3>${t("noResultsTitle")}</h3>
          <p class="center-summary">${t("noResultsText")}</p>
        </div>
      </article>
    `;

  refreshIcons();
}

function renderMap() {
  const lines = [
    `<span class="map-line" style="left: 23%; top: 45%; width: 225px; transform: rotate(-14deg);"></span>`,
    `<span class="map-line" style="left: 50%; top: 39%; width: 198px; transform: rotate(23deg);"></span>`,
    `<span class="map-line" style="left: 61%; top: 47%; width: 168px; transform: rotate(38deg);"></span>`,
  ].join("");

  const pins = centers
    .map(
      (center) => `
        <span class="map-pin" style="left:${center.map.x}%; top:${center.map.y}%;">
          <strong>${center.city}</strong>
          <span>${specialtyLabel(center.program)} · ${formatPrice(center.price)}</span>
        </span>
      `
    )
    .join("");

  worldMap.innerHTML = lines + pins;
}

function renderLeads() {
  document.querySelector("#leadBoard").innerHTML = leads
    .map(
      (lead) => `
        <article class="lead-card">
          <header>
            <h3>${lead.name}</h3>
            <span class="lead-stage">${lead.stage}</span>
          </header>
          <p>${lead.detail}</p>
          <div class="lead-actions">
            <button class="ghost-button" type="button">${icon("message-circle")} Message</button>
            <button class="primary-button compact" type="button">${icon("check")} Qualify</button>
          </div>
        </article>
      `
    )
    .join("");
  refreshIcons();
}

function renderPrograms() {
  document.querySelector("#programList").innerHTML = programs
    .map(
      (program) => `
        <article class="program-card">
          <header>
            <h3>${program.name}</h3>
            <span class="program-status ${program.status === "Waitlist" ? "waitlist" : ""}">${program.status}</span>
          </header>
          <p>${program.body}</p>
          <small>${program.demand}</small>
        </article>
      `
    )
    .join("");
}

function openCenter(centerId) {
  const center = centers.find((item) => item.id === centerId);
  if (!center) return;

  state.selectedCenter = center;
  document.querySelector("#modalImage").src = center.image;
  document.querySelector("#modalImage").alt = center.name;
  document.querySelector("#modalRegion").textContent = `${center.region} · ${center.city}`;
  document.querySelector("#modalTitle").textContent = center.name;
  document.querySelector("#modalSummary").textContent = center.summary[state.lang] || center.summary.en;
  document.querySelector("#modalContact").textContent = `${center.contact} · ${center.email}`;
  document.querySelector("#modalDetails").innerHTML = `
    <span><small>${t("languages")}</small><strong>${center.languages}</strong></span>
    <span><small>${t("stay")}</small><strong>${center.stay} days</strong></span>
    <span><small>${t("oversight")}</small><strong>${center.oversight}</strong></span>
    <span><small>${t("contact")}</small><strong>${center.phone}</strong></span>
  `;
  centerDialog.showModal();
  refreshIcons();
}

window.openCenterProfile = openCenter;

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  window.setTimeout(() => toast.classList.remove("show"), 2600);
}

function renderAll() {
  translateStatic();
  renderCenters();
  renderMap();
  renderLeads();
  renderPrograms();
  refreshIcons();
}

